def product_block(product: ProductInput) -> str:
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer or None,
        "specs": product.filled_specs,
        "description": product.description or None,
    }
    lines = ["<product>", json.dumps(payload, ensure_ascii=False, indent=2), "</product>"]
    empty = product.empty_fields()
    if empty:
        lines.append(f"Во входных данных пустые поля: {', '.join(empty)}.")
    return "\n".join(lines)


def generation_prompt(product: ProductInput) -> str:
    return f"{product_block(product)}\n\nПодготовь черновик карточки товара."


def verification_prompt(product: ProductInput, draft: CardDraft) -> str:
    card = draft.model_dump_json(indent=2, exclude={"missing"})
    return f"{product_block(product)}\n\n<card>\n{card}\n</card>\n\nПроверь черновик."


def repair_prompt(product: ProductInput, draft: CardDraft, issues: list[Issue]) -> str:
    notes = "\n".join(f"- {issue.message}" for issue in issues)
    return (
        f"{product_block(product)}\n\n<card>\n{draft.model_dump_json(indent=2)}\n</card>\n\n"
        f"Проверка нашла в черновике проблемы:\n{notes}\n\n"
        "Исправь черновик: устрани каждое замечание, остальное по возможности сохрани. "
        "Все требования к полям остаются в силе. Верни карточку целиком."
    )
